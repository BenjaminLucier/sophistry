import { describe, expect, it } from "vitest";
import { renderEntry } from "./render.ts";

const fixture = {
	packageName: "@example/shapes",
	wrapModule: "../wrap.js",
	items: [
		{ exportName: "rect", componentName: "Rect" },
		{ exportName: "circle", componentName: "Circle" },
	],
};

describe("renderEntry", () => {
	it("writes a header, one import and a component plus props type per definition, sorted", () => {
		expect(
			renderEntry(fixture),
		).toBe(`// @generated by @sophistry/codegen from "@example/shapes/definitions". Do not edit.
// Regenerate with \`pnpm --filter @sophistry/codegen generate\`.

import { circle, rect } from "@example/shapes";
import { type ComponentProps, wrap } from "../wrap.js";

/**
 * \`circle\` from \`@example/shapes\` as a component.
 *
 * @category Components
 */
export const Circle = wrap(circle);
/**
 * Props of {@link Circle}.
 *
 * @category Components
 */
export type CircleProps = ComponentProps<typeof circle>;

/**
 * \`rect\` from \`@example/shapes\` as a component.
 *
 * @category Components
 */
export const Rect = wrap(rect);
/**
 * Props of {@link Rect}.
 *
 * @category Components
 */
export type RectProps = ComponentProps<typeof rect>;
`);
	});

	it("breaks a long import over one name per line", () => {
		const items = [
			"alpha",
			"bravo",
			"charlie",
			"delta",
			"echo",
			"foxtrot",
			"golf",
		].map((exportName) => ({
			exportName,
			componentName: exportName[0]?.toUpperCase() + exportName.slice(1),
		}));
		const output = renderEntry({ ...fixture, items });
		expect(output).toContain("import {\n\talpha,\n\tbravo,");
		expect(output).toContain('\tgolf,\n} from "@example/shapes";');
	});

	it("writes an empty module for a package without definitions", () => {
		const output = renderEntry({ ...fixture, items: [] });
		expect(output).toContain(
			"// @example/shapes exports no definitions yet.\nexport {};\n",
		);
		expect(output).not.toContain("import");
	});

	it("rejects collisions, reserved names and non-PascalCase names", () => {
		expect(() =>
			renderEntry({
				...fixture,
				items: [
					{ exportName: "circle", componentName: "Circle" },
					{ exportName: "disc", componentName: "Circle" },
				],
			}),
		).toThrow(/"Circle" is generated for both circle and disc/);
		expect(() =>
			renderEntry({
				...fixture,
				reserved: ["Stage"],
				items: [{ exportName: "stage", componentName: "Stage" }],
			}),
		).toThrow(/"Stage" is reserved/);
		expect(() =>
			renderEntry({
				...fixture,
				reserved: ["CameraProps"],
				items: [{ exportName: "camera", componentName: "Camera" }],
			}),
		).toThrow(/"CameraProps" is reserved/);
		expect(() =>
			renderEntry({
				...fixture,
				items: [{ exportName: "circle", componentName: "circle" }],
			}),
		).toThrow(/not PascalCase/);
	});
});
