/**
 * Renders one generated entry file: a header, one import of the package's
 * definitions, and per definition a component and its props type.
 *
 * ```ts
 * export const Circle = wrap(circle);
 * export type CircleProps = ComponentProps<typeof circle>;
 * ```
 *
 * Pure (no file system), so it is tested on fixtures. Output is formatted the
 * way biome would format it, but the files are biome-ignored (`*.gen.ts`).
 */

/** One definition to generate: its export name and its component name. */
export interface EntryItem {
	/** The definition's export name in the source package (`circle`). */
	exportName: string;
	/** The component's name (`Circle`): the definition's `name` unless renamed. */
	componentName: string;
}

/** Input of {@link renderEntry}. */
export interface EntryInput {
	/** The source package (`@sophistry/core`). */
	packageName: string;
	/** The definitions, in any order (sorted by component name on output). */
	items: readonly EntryItem[];
	/** Names the binding's own entry exports. */
	reserved?: readonly string[];
	/** Module to import `wrap` and `ComponentProps` from. */
	wrapModule: string;
}

const PASCAL_CASE = /^[A-Z][A-Za-z0-9]*$/;
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** The command that regenerates the files, quoted in their header. */
export const GENERATE_COMMAND = "pnpm --filter @sophistry/codegen generate";

/**
 * Checks names: PascalCase component names, valid export names, no two
 * components (or their `Props` types) with one name, none reserved.
 *
 * @throws With every problem found, one per line.
 */
export function validateItems(input: EntryInput): void {
	const problems: string[] = [];
	const reserved = new Set(input.reserved ?? []);
	const taken = new Map<string, string>();
	for (const { exportName, componentName } of input.items) {
		if (!IDENTIFIER.test(exportName)) {
			problems.push(`"${exportName}" is not a valid export name.`);
		}
		if (!PASCAL_CASE.test(componentName)) {
			problems.push(
				`${exportName}: component name "${componentName}" is not PascalCase.`,
			);
		}
		for (const name of [componentName, `${componentName}Props`]) {
			if (reserved.has(name)) {
				problems.push(
					`${exportName}: "${name}" is reserved by the binding's own exports; add a rename in codegen's targets.ts.`,
				);
			}
			const other = taken.get(name);
			if (other !== undefined) {
				problems.push(
					`"${name}" is generated for both ${other} and ${exportName}; add a rename in codegen's targets.ts.`,
				);
			} else taken.set(name, exportName);
		}
	}
	if (problems.length > 0) {
		throw new Error(
			`${input.packageName}: cannot generate components:\n  ${problems.join("\n  ")}`,
		);
	}
}

function header(packageName: string): string {
	return [
		`// @generated by @sophistry/codegen from "${packageName}/definitions". Do not edit.`,
		`// Regenerate with \`${GENERATE_COMMAND}\`.`,
		"",
	].join("\n");
}

/** A named import, on one line when it fits in 80 columns, else one name per line. */
function importLine(names: readonly string[], from: string): string {
	const single = `import { ${names.join(", ")} } from "${from}";`;
	if (single.length <= 80) return single;
	return `import {\n${names.map((name) => `\t${name},\n`).join("")}} from "${from}";`;
}

/**
 * Renders the generated entry for one package in one binding.
 *
 * @throws When names are invalid or collide (see {@link validateItems}).
 */
export function renderEntry(input: EntryInput): string {
	validateItems(input);
	const items = [...input.items].sort((a, b) =>
		a.componentName < b.componentName
			? -1
			: a.componentName > b.componentName
				? 1
				: 0,
	);
	if (items.length === 0) {
		return `${header(input.packageName)}\n// ${input.packageName} exports no definitions yet.\nexport {};\n`;
	}
	const exportNames = [...new Set(items.map((item) => item.exportName))].sort();
	const lines = [
		header(input.packageName),
		importLine(exportNames, input.packageName),
		`import { type ComponentProps, wrap } from "${input.wrapModule}";`,
	];
	for (const { exportName, componentName } of items) {
		lines.push(
			"",
			`/**\n * \`${exportName}\` from \`${input.packageName}\` as a component.\n *\n * @category Components\n */`,
			`export const ${componentName} = wrap(${exportName});`,
			`/**\n * Props of {@link ${componentName}}.\n *\n * @category Components\n */`,
			`export type ${componentName}Props = ComponentProps<typeof ${exportName}>;`,
		);
	}
	return `${lines.join("\n")}\n`;
}
